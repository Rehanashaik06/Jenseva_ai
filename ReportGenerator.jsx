import { useState } from 'react';
import { reportData } from '../data/mockData';
import { FileText, Download, Printer } from 'lucide-react';

export default function ReportGenerator() {
  const [generated, setGenerated] = useState(false);
  const [loading, setLoading] = useState(false);

  const handleGenerate = () => {
    setLoading(true);
    setTimeout(() => { setLoading(false); setGenerated(true); }, 1800);
  };

  const handlePrint = () => window.print();

  return (
    <div className="fade-in">
      <div className="section-header">
        <div style={{
          width: 42, height: 42, borderRadius: 12,
          background: 'rgba(245,158,11,0.15)', border: '1px solid rgba(245,158,11,0.3)',
          display: 'flex', alignItems: 'center', justifyContent: 'center'
        }}>
          <FileText size={22} color="#f59e0b" />
        </div>
        <div>
          <h2 style={{ marginBottom: 2 }}>Report Generator</h2>
          <p style={{ fontSize: 13, color: 'var(--text-muted)', fontWeight: 400 }}>
            Auto-generate monthly constituency reports ready for ministry, press, and public meetings.
          </p>
        </div>
      </div>

      {!generated ? (
        <div style={{ display: 'flex', flexDirection: 'column', alignItems: 'center', justifyContent: 'center', minHeight: 400, gap: 24 }}>
          <div style={{
            width: 100, height: 100, borderRadius: '50%',
            background: 'rgba(245,158,11,0.1)', border: '2px solid rgba(245,158,11,0.3)',
            display: 'flex', alignItems: 'center', justifyContent: 'center', fontSize: 48
          }}>📄</div>
          <div style={{ textAlign: 'center', maxWidth: 500 }}>
            <h3 style={{ fontSize: 24, fontWeight: 700, marginBottom: 10 }}>Monthly Constituency Report</h3>
            <p style={{ color: '#94a3b8', marginBottom: 8 }}>
              Generate a comprehensive {reportData.month} report for <strong style={{ color: 'white' }}>{reportData.constituency}</strong>.
            </p>
            <p style={{ fontSize: 13, color: '#64748b' }}>
              Includes: Issue summary · Budget recommendations · Ward priorities · MP action plan
            </p>
          </div>
          <button
            className="btn-primary"
            style={{ fontSize: 16, padding: '16px 40px' }}
            onClick={handleGenerate}
            disabled={loading}
          >
            {loading ? (
              <span style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
                <span style={{
                  width: 18, height: 18, border: '2px solid rgba(255,255,255,0.3)',
                  borderTopColor: 'white', borderRadius: '50%', animation: 'spin 0.8s linear infinite',
                  display: 'inline-block'
                }} />
                Generating Report...
              </span>
            ) : (
              <><FileText size={18} /> Generate Monthly Constituency Report</>
            )}
          </button>
          <style>{`@keyframes spin { to { transform: rotate(360deg); } }`}</style>
        </div>
      ) : (
        <div>
          {/* Action buttons */}
          <div style={{ display: 'flex', gap: 12, marginBottom: 24, justifyContent: 'flex-end', flexWrap: 'wrap' }}>
            <button className="btn-secondary" onClick={() => setGenerated(false)}>
              ↩ Regenerate
            </button>
            <button className="btn-primary" onClick={handlePrint}>
              <Printer size={16} /> Download / Print Report
            </button>
          </div>

          {/* Report preview */}
          <div className="report-page" id="printable-report">
            {/* Header */}
            <div style={{
              borderBottom: '3px solid #1e3a8a', paddingBottom: 24, marginBottom: 28,
              display: 'flex', justifyContent: 'space-between', alignItems: 'flex-start'
            }}>
              <div>
                <div style={{
                  display: 'inline-flex', alignItems: 'center', gap: 8,
                  background: '#1e3a8a', color: 'white', padding: '4px 14px',
                  borderRadius: 6, fontSize: 11, fontWeight: 700, letterSpacing: 1, marginBottom: 12
                }}>🏛️ GOVERNMENT OF INDIA</div>
                <h1 style={{ fontSize: 26, fontWeight: 900, color: '#0b1437', fontFamily: 'Outfit', marginBottom: 4 }}>
                  Monthly Constituency Development Report
                </h1>
                <p style={{ fontSize: 14, color: '#475569' }}>{reportData.constituency} | {reportData.month}</p>
                <p style={{ fontSize: 13, color: '#1e3a8a', fontWeight: 600 }}>{reportData.mp}</p>
              </div>
              <div style={{ textAlign: 'right' }}>
                <div style={{ fontSize: 12, color: '#64748b' }}>Generated by</div>
                <div style={{ fontSize: 16, fontWeight: 800, color: '#1e3a8a' }}>JanSeva AI</div>
                <div style={{ fontSize: 11, color: '#94a3b8' }}>Constituency Intelligence Platform</div>
                <div style={{ fontSize: 11, color: '#94a3b8', marginTop: 4 }}>{reportData.month}</div>
              </div>
            </div>

            {/* Key metrics */}
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(4, 1fr)', gap: 16, marginBottom: 28 }}>
              {[
                { label: 'Total Issues', value: reportData.totalIssues, color: '#1e40af' },
                { label: 'Resolved', value: reportData.resolved, color: '#059669' },
                { label: 'Urgent Pending', value: reportData.urgent, color: '#dc2626' },
                { label: 'Citizens Impacted', value: reportData.citizensImpacted.toLocaleString(), color: '#d97706' },
              ].map(s => (
                <div key={s.label} style={{
                  background: `${s.color}0f`, border: `1px solid ${s.color}25`,
                  borderRadius: 10, padding: 14, textAlign: 'center'
                }}>
                  <div style={{ fontSize: 26, fontWeight: 900, color: s.color, fontFamily: 'Outfit' }}>{s.value}</div>
                  <div style={{ fontSize: 11, color: '#64748b', textTransform: 'uppercase', letterSpacing: 0.5 }}>{s.label}</div>
                </div>
              ))}
            </div>

            {/* Top issues */}
            <h2 style={{ fontSize: 17, fontWeight: 800, color: '#0f172a', borderBottom: '2px solid #e2e8f0', paddingBottom: 8, marginBottom: 16 }}>
              📋 Top Issues by Category
            </h2>
            <table style={{ width: '100%', borderCollapse: 'collapse', marginBottom: 28, fontSize: 13 }}>
              <thead>
                <tr style={{ background: '#f1f5f9' }}>
                  <th style={{ padding: '10px 14px', textAlign: 'left', color: '#1e3a8a', fontSize: 12 }}>Category</th>
                  <th style={{ padding: '10px 14px', textAlign: 'center', color: '#1e3a8a', fontSize: 12 }}>Issues</th>
                  <th style={{ padding: '10px 14px', textAlign: 'left', color: '#1e3a8a', fontSize: 12 }}>Share</th>
                </tr>
              </thead>
              <tbody>
                {reportData.topCategories.map((cat, i) => (
                  <tr key={cat.name} style={{ borderBottom: '1px solid #f1f5f9', background: i % 2 === 0 ? 'white' : '#fafafa' }}>
                    <td style={{ padding: '9px 14px', fontWeight: 600, color: '#334155' }}>{cat.name}</td>
                    <td style={{ padding: '9px 14px', textAlign: 'center', fontWeight: 700, color: '#1e40af' }}>{cat.count}</td>
                    <td style={{ padding: '9px 14px' }}>
                      <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                        <div style={{ flex: 1, height: 6, background: '#e2e8f0', borderRadius: 3 }}>
                          <div style={{ width: `${cat.percentage}%`, height: '100%', background: '#1e40af', borderRadius: 3 }} />
                        </div>
                        <span style={{ fontSize: 12, color: '#64748b' }}>{cat.percentage}%</span>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>

            {/* Budget */}
            <h2 style={{ fontSize: 17, fontWeight: 800, color: '#0f172a', borderBottom: '2px solid #e2e8f0', paddingBottom: 8, marginBottom: 16 }}>
              💰 Budget Recommendation
            </h2>
            <table style={{ width: '100%', borderCollapse: 'collapse', marginBottom: 28, fontSize: 13 }}>
              <thead>
                <tr style={{ background: '#f1f5f9' }}>
                  <th style={{ padding: '10px 14px', textAlign: 'left', color: '#1e3a8a', fontSize: 12 }}>Category</th>
                  <th style={{ padding: '10px 14px', textAlign: 'right', color: '#1e3a8a', fontSize: 12 }}>Amount</th>
                  <th style={{ padding: '10px 14px', textAlign: 'center', color: '#1e3a8a', fontSize: 12 }}>Priority</th>
                </tr>
              </thead>
              <tbody>
                {reportData.budgetRecommendation.map((b, i) => (
                  <tr key={b.category} style={{ borderBottom: '1px solid #f1f5f9', background: i % 2 === 0 ? 'white' : '#fafafa' }}>
                    <td style={{ padding: '9px 14px', color: '#334155' }}>{b.category}</td>
                    <td style={{ padding: '9px 14px', textAlign: 'right', fontWeight: 700, color: '#0f172a' }}>{b.amount}</td>
                    <td style={{ padding: '9px 14px', textAlign: 'center' }}>
                      <span style={{
                        fontSize: 11, padding: '2px 8px', borderRadius: 6, fontWeight: 700,
                        background: b.priority === 'Immediate' ? '#fef2f2' : b.priority === 'High' ? '#fffbeb' : '#f0fdf4',
                        color: b.priority === 'Immediate' ? '#dc2626' : b.priority === 'High' ? '#d97706' : '#059669'
                      }}>{b.priority}</span>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>

            {/* Ward priority */}
            <h2 style={{ fontSize: 17, fontWeight: 800, color: '#0f172a', borderBottom: '2px solid #e2e8f0', paddingBottom: 8, marginBottom: 16 }}>
              🗺️ Ward Priority Summary
            </h2>
            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(4, 1fr)', gap: 10, marginBottom: 28 }}>
              {reportData.wardPriority.map(w => (
                <div key={w.ward} style={{
                  background: w.status === 'Critical' ? '#fef2f2' : w.status === 'High' ? '#fffbeb' : '#f0fdf4',
                  border: `1px solid ${w.status === 'Critical' ? '#fecaca' : w.status === 'High' ? '#fde68a' : '#bbf7d0'}`,
                  borderRadius: 8, padding: 12, textAlign: 'center'
                }}>
                  <div style={{ fontSize: 12, fontWeight: 700, color: '#334155', marginBottom: 4 }}>{w.ward}</div>
                  <div style={{ fontSize: 22, fontWeight: 900, color: w.status === 'Critical' ? '#dc2626' : w.status === 'High' ? '#d97706' : '#059669' }}>{w.score}</div>
                  <div style={{ fontSize: 10, color: '#64748b' }}>{w.status}</div>
                </div>
              ))}
            </div>

            {/* MP Action Plan */}
            <h2 style={{ fontSize: 17, fontWeight: 800, color: '#0f172a', borderBottom: '2px solid #e2e8f0', paddingBottom: 8, marginBottom: 16 }}>
              🎯 Suggested MP Action Plan
            </h2>
            <ol style={{ paddingLeft: 20, color: '#334155', lineHeight: 2, fontSize: 13 }}>
              {reportData.mpActionPlan.map((a, i) => (
                <li key={i} style={{ marginBottom: 4 }}>{a}</li>
              ))}
            </ol>

            {/* Footer */}
            <div style={{
              marginTop: 36, paddingTop: 20, borderTop: '2px solid #e2e8f0',
              display: 'flex', justifyContent: 'space-between', fontSize: 11, color: '#94a3b8'
            }}>
              <span>Generated by JanSeva AI — Constituency Intelligence Platform</span>
              <span>Confidential — For Official Use</span>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
